CREATE OR REPLACE FUNCTION public.orbitfs_server_allowed()
 RETURNS boolean
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO 'public', 'private', 'extensions'
AS $function$
  select coalesce(
    ((current_setting('request.headers', true))::jsonb ->> 'x-orbitfs-secret') =
      (select value from private.orbitfs_runtime_config where key='server_secret')
    or encode(extensions.digest(convert_to(coalesce((current_setting('request.headers', true))::jsonb ->> 'x-orbitfs-secret',''),'UTF8'),'sha256'),'hex') =
      (select value from private.orbitfs_runtime_config where key='mcp_server_secret_sha256'),
    false
  );
$function$


CREATE OR REPLACE FUNCTION public.orbitfs_touch_updated_at()
 RETURNS trigger
 LANGUAGE plpgsql
 SET search_path TO 'pg_catalog'
AS $function$
begin
  new.updated_at = now();
  return new;
end;
$function$


CREATE OR REPLACE FUNCTION public.revoke_mcp_oauth_for_client()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$ begin if new.status is distinct from old.status and new.status <> 'active' then update public.mcp_oauth_tokens set revoked_at = coalesce(revoked_at, now()) where client_id = new.id and revoked_at is null; end if; return new; end; $function$


CREATE OR REPLACE FUNCTION public.revoke_mcp_oauth_on_session_disconnect()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$ begin if new.status is distinct from old.status and new.status = 'revoked' and new.client_id is not null then update public.mcp_oauth_tokens set revoked_at = coalesce(revoked_at, now()) where client_id = new.client_id and revoked_at is null; end if; return new; end; $function$


